import { db } from '../src/lib/db'

async function stats() {
  const customers = await db.customer.count()
  const leads = await db.lead.count()
  const quotes = await db.quote.count()
  const orders = await db.order.count()
  const orderBreakdown = await db.order.groupBy({ by: ['status'], _count: { _all: true } })
  const units = await db.inventoryUnit.count()
  const unitStatuses = await db.inventoryUnit.groupBy({ by: ['status'], _count: { _all: true } })
  const warranties = await db.warranty.count()
  const warrantyStatuses = await db.warranty.groupBy({ by: ['status'], _count: { _all: true } })
  const payments = await db.payment.count()
  const paymentMethods = await db.payment.groupBy({ by: ['method'], _count: { _all: true }, _sum: { amountPaise: true } })
  const invoices = await db.invoice.count()
  const dispatches = await db.dispatch.count()
  const installations = await db.installation.count()
  const tickets = await db.serviceTicket.count()
  const minDate = await db.order.findFirst({ orderBy: { createdAt: 'asc' }, select: { createdAt: true } })
  const maxDate = await db.order.findFirst({ orderBy: { createdAt: 'desc' }, select: { createdAt: true } })

  console.log('=== DATABASE VERIFICATION STATS ===')
  console.log('Customers:      ', customers)
  console.log('Leads:          ', leads)
  console.log('Quotes:         ', quotes)
  console.log('Orders:         ', orders)
  console.log('Order Statuses: ', JSON.stringify(orderBreakdown))
  console.log('Inventory Units:', units)
  console.log('Unit Statuses:  ', JSON.stringify(unitStatuses))
  console.log('Warranties:     ', warranties)
  console.log('Warranty Status:', JSON.stringify(warrantyStatuses))
  console.log('Payments:       ', payments)
  console.log('Payment Methods:', JSON.stringify(paymentMethods.map(m => ({ method: m.method, count: m._count._all, totalINR: (m._sum.amountPaise || 0)/100 }))))
  console.log('Invoices:       ', invoices)
  console.log('Dispatches:     ', dispatches)
  console.log('Installations:  ', installations)
  console.log('Service Tickets:', tickets)
  console.log('Date Span:      ', minDate?.createdAt.toISOString().slice(0, 10), 'to', maxDate?.createdAt.toISOString().slice(0, 10))
}

stats().catch(console.error).finally(async () => {
  await db.$disconnect()
  process.exit(0)
})

